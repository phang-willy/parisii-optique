/**
 * Editorial homepage metadata. Services cited here exist on the homepage.
 *
 * @return array{title:string,description:string,h1:string}
 */
function parisii_optique_front_page_seo() {
    return [
        'title'       => 'Opticien à Cormeilles-en-Parisis — Parisii Optique',
        'description' => 'Parisii Optique, votre opticien à Cormeilles-en-Parisis. Découvrez nos lunettes de vue et de soleil, nos verres et nos conseils personnalisés.',
        'h1'          => 'Votre opticien à Cormeilles-en-Parisis',
    ];
}

/**
 * Whether another plugin already prints SEO tags.
 *
 * @return bool
 */
function parisii_optique_seo_plugin_active() {
    return defined('WPSEO_VERSION') || defined('RANK_MATH_VERSION') || defined('SEOPRESS_VERSION') || defined('AIOSEO_VERSION');
}

/**
 * Page IDs that must stay out of the search results.
 *
 * @return int[]
 */
function parisii_optique_transactional_page_ids() {
    static $ids = null;
    if (is_array($ids)) {
        return $ids;
    }

    $ids = [];
    foreach (['panier', 'commander', 'mon-compte', 'cart', 'checkout', 'my-account'] as $slug) {
        $page = get_page_by_path($slug);
        if ($page instanceof WP_Post) {
            $ids[] = (int) $page->ID;
        }
    }

    if (function_exists('wc_get_page_id')) {
        foreach (['cart', 'checkout', 'myaccount'] as $key) {
            $page_id = (int) wc_get_page_id($key);
            if ($page_id > 0) {
                $ids[] = $page_id;
            }
        }
    }

    $ids = array_values(array_unique($ids));

    return $ids;
}

/**
 * Whether the current request is a cart, checkout or account page.
 *
 * @return bool
 */
function parisii_optique_is_transactional_request() {
    if (function_exists('is_cart') && (is_cart() || is_checkout() || is_account_page())) {
        return true;
    }

    if (!is_singular()) {
        return false;
    }

    return in_array((int) get_queried_object_id(), parisii_optique_transactional_page_ids(), true);
}

/**
 * Generated titles previously stored by the SEO box.
 *
 * @param WP_Post $post Post object.
 * @return string[]
 */
function parisii_optique_generated_title_candidates($post) {
    $site_title = get_bloginfo('name');
    $hierarchy = function_exists('parisii_optique_build_hierarchy_title')
        ? parisii_optique_build_hierarchy_title($post)
        : $post->post_title;

    return [
        $site_title . ' - ' . $hierarchy,
        $site_title . ' - ' . $post->post_title,
        $hierarchy,
    ];
}

/**
 * Generated descriptions previously stored by the SEO box.
 *
 * @param WP_Post $post Post object.
 * @return string[]
 */
function parisii_optique_generated_description_candidates($post) {
    $site_title = get_bloginfo('name');
    $site_description = get_bloginfo('description');
    $hierarchy = function_exists('parisii_optique_build_hierarchy_title')
        ? parisii_optique_build_hierarchy_title($post)
        : $post->post_title;

    return [
        $site_title . ' - ' . $hierarchy . ' - ' . $site_description,
        $site_description,
    ];
}

/**
 * Whether a stored meta value is empty or one of the automatic strings.
 *
 * @param string   $value      Stored value.
 * @param string[] $generated  Automatic candidates.
 * @return bool
 */
function parisii_optique_meta_is_autogenerated($value, array $generated) {
    $value = trim(wp_strip_all_tags((string) $value));
    if ($value === '') {
        return true;
    }

    foreach ($generated as $candidate) {
        if ($value === trim(wp_strip_all_tags((string) $candidate))) {
            return true;
        }
    }

    return false;
}

/**
 * Title and description used by the document title and the social tags.
 *
 * @return array{title:string,description:string,managed:bool}
 */
function parisii_optique_seo_document() {
    $site_description = wp_strip_all_tags(get_bloginfo('description'));
    $document = [
        'title'       => '',
        'description' => $site_description,
        'managed'     => false,
    ];

    if (is_front_page()) {
        $front = parisii_optique_front_page_seo();
        $document['title'] = $front['title'];
        $document['description'] = $front['description'];
        $post = get_queried_object();
        if ($post instanceof WP_Post) {
            $custom_title = (string) get_post_meta($post->ID, '_parisii_meta_title', true);
            $custom_description = (string) get_post_meta($post->ID, '_parisii_meta_description', true);
            if (!parisii_optique_meta_is_autogenerated($custom_title, parisii_optique_generated_title_candidates($post))) {
                $document['title'] = wp_strip_all_tags($custom_title);
            }
            if (!parisii_optique_meta_is_autogenerated($custom_description, parisii_optique_generated_description_candidates($post))) {
                $document['description'] = wp_strip_all_tags($custom_description);
            }
        }
        $document['managed'] = $document['title'] !== '';

        return $document;
    }

    if (is_singular()) {
        $post = get_queried_object();
        if ($post instanceof WP_Post) {
            $hierarchy = function_exists('parisii_optique_build_hierarchy_title')
                ? parisii_optique_build_hierarchy_title($post)
                : $post->post_title;
            $custom_title = (string) get_post_meta($post->ID, '_parisii_meta_title', true);
            $custom_description = (string) get_post_meta($post->ID, '_parisii_meta_description', true);
            $document['title'] = parisii_optique_meta_is_autogenerated($custom_title, parisii_optique_generated_title_candidates($post))
                ? $hierarchy
                : wp_strip_all_tags($custom_title);
            $document['description'] = parisii_optique_meta_is_autogenerated($custom_description, parisii_optique_generated_description_candidates($post))
                ? trim($hierarchy . '. ' . $site_description)
                : wp_strip_all_tags($custom_description);
            $document['managed'] = $document['title'] !== '';
        }
    } elseif (is_post_type_archive()) {
        $archive_title = post_type_archive_title('', false);
        if (is_string($archive_title) && trim($archive_title) !== '') {
            $document['title'] = wp_strip_all_tags($archive_title);
            $document['managed'] = true;
        }
    } elseif (is_category() || is_tag() || is_tax()) {
        $term_title = single_term_title('', false);
        if (is_string($term_title) && trim($term_title) !== '') {
            $document['title'] = wp_strip_all_tags($term_title);
            $document['managed'] = true;
        }
        $description = term_description();
        if (is_string($description) && $description !== '') {
            $document['description'] = wp_strip_all_tags($description);
        }
    } elseif (is_author()) {
        $author = get_queried_object();
        if ($author instanceof WP_User && $author->display_name !== '') {
            $document['title'] = wp_strip_all_tags($author->display_name);
            $document['managed'] = true;
        }
    } elseif (is_date()) {
        if (is_day()) {
            $date_title = get_the_date();
        } elseif (is_month()) {
            $date_title = get_the_date(_x('F Y', 'monthly archives date format'));
        } else {
            $date_title = get_the_date(_x('Y', 'yearly archives date format'));
        }
        if (is_string($date_title) && $date_title !== '') {
            $document['title'] = wp_strip_all_tags($date_title);
            $document['managed'] = true;
        }
    } elseif (is_home()) {
        $home_title = single_post_title('', false);
        if (is_string($home_title) && trim($home_title) !== '') {
            $document['title'] = wp_strip_all_tags($home_title);
            $document['managed'] = true;
        }
    } elseif (is_search()) {
        $document['title'] = 'Recherche';
        $document['managed'] = true;
    } elseif (is_404()) {
        $document['title'] = wp_strip_all_tags(__('Page not found'));
        $document['managed'] = $document['title'] !== '';
    }

    return $document;
}

/**
 * Document title parts.
 *
 * @param array<string,string> $title Title parts.
 * @return array<string,string>
 */
function parisii_optique_document_title_parts($title) {
    if (parisii_optique_seo_plugin_active()) {
        return $title;
    }

    $document = parisii_optique_seo_document();

    return parisii_optique_finalize_document_title_parts(
        $title,
        !empty($document['managed']) ? $document['title'] : '',
        wp_strip_all_tags(get_bloginfo('name')),
        is_front_page()
    );
}
add_filter('document_title_parts', 'parisii_optique_document_title_parts');

/**
 * Absolute canonical URL for the current request.
 *
 * @return string
 */
function parisii_optique_canonical_url() {
    $url = '';

    if (is_singular()) {
        $url = (string) wp_get_canonical_url();
    } elseif (is_front_page()) {
        $url = home_url('/');
    } elseif (is_home()) {
        $posts_page = (int) get_option('page_for_posts');
        $url = $posts_page ? (string) get_permalink($posts_page) : home_url('/');
    } elseif (is_post_type_archive() || is_category() || is_tag() || is_tax() || is_author() || is_date()) {
        $paged = max(1, (int) get_query_var('paged'), (int) get_query_var('page'));
        $url = (string) get_pagenum_link($paged);
    }

    if ($url === '') {
        $url = home_url('/');
    }

    if (parisii_is_production()) {
        $url = parisii_optique_rewrite_origin($url, parisii_optique_official_origin());
    }

    return $url;
}

/**
 * Image used for Open Graph, without invented dimensions.
 *
 * @return array{url:string,width:int,height:int,mime:string}
 */
function parisii_optique_seo_image() {
    $image = [
        'url'    => '',
        'width'  => 0,
        'height' => 0,
        'mime'   => '',
    ];

    $post = get_queried_object();
    if ($post instanceof WP_Post) {
        $custom = (string) get_post_meta($post->ID, '_parisii_og_image', true);
        if ($custom !== '') {
            $image['url'] = $custom;
        } elseif (has_post_thumbnail($post)) {
            $src = wp_get_attachment_image_src(get_post_thumbnail_id($post), 'large');
            if (is_array($src)) {
                $image['url'] = (string) $src[0];
                $image['width'] = (int) $src[1];
                $image['height'] = (int) $src[2];
            }
        }
    }

    if ($image['url'] === '' && has_custom_logo()) {
        $logo_id = (int) get_theme_mod('custom_logo');
        $src = wp_get_attachment_image_src($logo_id, 'large');
        if (is_array($src)) {
            $image['url'] = (string) $src[0];
            $image['width'] = (int) $src[1];
            $image['height'] = (int) $src[2];
            $image['mime'] = (string) get_post_mime_type($logo_id);
        }
    }

    if ($image['url'] !== '' && $image['mime'] === '') {
        $path = (string) wp_parse_url($image['url'], PHP_URL_PATH);
        $extension = strtolower(pathinfo($path, PATHINFO_EXTENSION));
        $mimes = [
            'jpg'  => 'image/jpeg',
            'jpeg' => 'image/jpeg',
            'png'  => 'image/png',
            'webp' => 'image/webp',
            'gif'  => 'image/gif',
        ];
        $image['mime'] = $mimes[$extension] ?? '';
    }

    return $image;
}

/**
 * Print description, social tags and the single canonical link.
 */
function parisii_optique_output_seo_meta_tags() {
    if (is_admin() || is_feed() || parisii_optique_seo_plugin_active()) {
        return;
    }

    $document = parisii_optique_seo_document();
    $social_title = $document['title'] !== '' ? $document['title'] : wp_strip_all_tags(get_bloginfo('name'));
    $canonical = parisii_optique_canonical_url();
    $image = parisii_optique_seo_image();
    $og_type = 'website';
    if (is_singular('post')) {
        $og_type = 'article';
    } elseif (function_exists('is_product') && is_product()) {
        $og_type = 'product';
    }

    echo "\n<!-- SEO Meta Tags -->\n";
    echo '<meta name="description" content="' . esc_attr($document['description']) . '">' . "\n";
    echo '<meta property="og:type" content="' . esc_attr($og_type) . '">' . "\n";
    echo '<meta property="og:title" content="' . esc_attr($social_title) . '">' . "\n";
    echo '<meta property="og:description" content="' . esc_attr($document['description']) . '">' . "\n";
    echo '<meta property="og:url" content="' . esc_url($canonical) . '">' . "\n";
    echo '<meta property="og:site_name" content="' . esc_attr(get_bloginfo('name')) . '">' . "\n";
    echo '<meta property="og:locale" content="fr_FR">' . "\n";

    if ($image['url'] !== '') {
        echo '<meta property="og:image" content="' . esc_url($image['url']) . '">' . "\n";
        if ($image['width'] > 0 && $image['height'] > 0) {
            echo '<meta property="og:image:width" content="' . esc_attr((string) $image['width']) . '">' . "\n";
            echo '<meta property="og:image:height" content="' . esc_attr((string) $image['height']) . '">' . "\n";
        }
        if ($image['mime'] !== '') {
            echo '<meta property="og:image:type" content="' . esc_attr($image['mime']) . '">' . "\n";
        }
        echo '<meta name="twitter:card" content="summary_large_image">' . "\n";
        echo '<meta name="twitter:image" content="' . esc_url($image['url']) . '">' . "\n";
    } else {
        echo '<meta name="twitter:card" content="summary">' . "\n";
    }

    echo '<meta name="twitter:title" content="' . esc_attr($social_title) . '">' . "\n";
    echo '<meta name="twitter:description" content="' . esc_attr($document['description']) . '">' . "\n";
    echo '<link rel="canonical" href="' . esc_url($canonical) . '">' . "\n";
    echo "<!-- End SEO Meta Tags -->\n\n";
}
add_action('wp_head', 'parisii_optique_output_seo_meta_tags', 1);

/**
 * Core also prints a canonical link. Keep only the theme one.
 */
function parisii_optique_disable_core_canonical() {
    if (!parisii_optique_seo_plugin_active()) {
        remove_action('wp_head', 'rel_canonical');
    }
}
add_action('wp', 'parisii_optique_disable_core_canonical');

/**
 * Robots directives.
 *
 * @param array<string,bool|string> $robots Robots tokens.
 * @return array<string,bool|string>
 */
function parisii_optique_filter_robots($robots) {
    if (!parisii_is_production()) {
        $robots['noindex'] = true;
        $robots['nofollow'] = true;
        unset($robots['index'], $robots['follow']);

        return $robots;
    }

    if (parisii_optique_is_transactional_request()) {
        $robots['noindex'] = true;
        $robots['follow'] = true;
        unset($robots['index'], $robots['nofollow']);
    }

    return $robots;
}
add_filter('wp_robots', 'parisii_optique_filter_robots', 99);

/**
 * Disable the core sitemap outside production.
 *
 * A global robots.txt disallow is intentionally not added: crawlers must be
 * able to read the noindex directive.
 *
 * @param bool $enabled Whether sitemaps are enabled.
 * @return bool
 */
function parisii_optique_sitemaps_enabled($enabled) {
    if (!parisii_is_production()) {
        return false;
    }

    return $enabled;
}
add_filter('wp_sitemaps_enabled', 'parisii_optique_sitemaps_enabled');

/**
 * Register sitemap providers once production is known.
 *
 * Core registers them on init priority 10. If WP_ENVIRONMENT_TYPE is defined
 * later in the same request, that first pass skips every provider and the
 * index stays empty.
 */
function parisii_optique_ensure_sitemap_providers() {
    if (!parisii_is_production() || "0" === (string) get_option("blog_public")) {
        return;
    }

    $sitemaps = wp_sitemaps_get_server();
    if ($sitemaps->registry->get_providers()) {
        return;
    }

    $sitemaps->register_sitemaps();
    add_filter("robots_txt", [$sitemaps, "add_robots"], 0, 2);
}
add_action("template_redirect", "parisii_optique_ensure_sitemap_providers", 9);

/**
 * Keep transactional pages out of the page sitemap.
 *
 * @param array<string,mixed> $args      Query args.
 * @param string              $post_type Post type.
 * @return array<string,mixed>
 */
function parisii_optique_sitemap_exclude_transactional_pages($args, $post_type) {
    if ($post_type !== 'page') {
        return $args;
    }

    $excluded = parisii_optique_transactional_page_ids();
    if (!$excluded) {
        return $args;
    }

    $args['post__not_in'] = array_values(array_unique(array_merge(
        isset($args['post__not_in']) && is_array($args['post__not_in']) ? $args['post__not_in'] : [],
        $excluded
    )));

    return $args;
}
add_filter('wp_sitemaps_posts_query_args', 'parisii_optique_sitemap_exclude_transactional_pages', 10, 2);

/**
 * Resolve an internal page URL from one or more slugs.
 *
 * @param string|string[] $slugs         Candidate slugs, most relevant first.
 * @param string          $fallback_path Path used when no page exists.
 * @return string
 */
function parisii_optique_get_page_url($slugs, $fallback_path = '/') {
    foreach ((array) $slugs as $slug) {
        $page = get_page_by_path((string) $slug);
        if ($page instanceof WP_Post) {
            $url = get_permalink($page);
            if (is_string($url) && $url !== '') {
                return $url;
            }
        }
    }

    return home_url($fallback_path);
}

/**
 * Local business structured data from the values shown on the site.
 */
function parisii_optique_output_local_business_schema() {
    if (is_admin() || is_feed()) {
        return;
    }

    $street = (string) get_theme_mod('address_street', '12 Véloroute Sequana');
    $city_line = (string) get_theme_mod('address_city', '95240 Cormeilles-en-Parisis');
    $city = parisii_optique_split_city_line($city_line);
    $phone = (string) get_theme_mod('phone_number', '01 34 29 05 05');
    $email = (string) get_theme_mod('email_address', 'contact@parisii-optique.fr');
    $hours = function_exists('parisii_optique_get_opening_hours') ? parisii_optique_get_opening_hours() : [];
    $image = parisii_optique_seo_image();
    $same_as = [];

    if (function_exists('parisii_optique_sanitize_instagram_account')) {
        $instagram = parisii_optique_sanitize_instagram_account((string) get_theme_mod('instagram_account', 'parisii.optique'));
        if ($instagram !== '') {
            $same_as[] = 'https://www.instagram.com/' . rawurlencode($instagram) . '/';
        }
    }
    if (function_exists('parisii_optique_sanitize_facebook_url')) {
        $facebook = parisii_optique_sanitize_facebook_url((string) get_theme_mod('facebook_url', ''));
        if ($facebook !== '') {
            $same_as[] = $facebook;
        }
    }

    $data = [
        '@context' => 'https://schema.org',
        '@type'    => 'Optician',
        'name'     => get_bloginfo('name'),
        'url'      => parisii_is_production() ? parisii_optique_official_origin() . '/' : home_url('/'),
        'address'  => [
            '@type'           => 'PostalAddress',
            'streetAddress'   => $street,
            'addressLocality' => $city['locality'],
            'postalCode'      => $city['postal_code'],
            'addressCountry'  => 'FR',
        ],
        'openingHoursSpecification' => parisii_optique_opening_hours_schema($hours),
    ];

    if ($phone !== '') {
        $data['telephone'] = $phone;
    }
    if ($email !== '') {
        $data['email'] = $email;
    }
    if ($image['url'] !== '') {
        $data['image'] = $image['url'];
    }
    if ($same_as) {
        $data['sameAs'] = $same_as;
    }

    $embed = (string) get_theme_mod('google_maps_embed', '');
    $coordinates = parisii_optique_maps_embed_coordinates(parisii_optique_maps_iframe_src($embed));
    if ($coordinates) {
        $data['geo'] = [
            '@type'     => 'GeoCoordinates',
            'latitude'  => $coordinates['latitude'],
            'longitude' => $coordinates['longitude'],
        ];
    }

    $json = wp_json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    if (!is_string($json)) {
        return;
    }

    echo '<script type="application/ld+json">' . str_replace('</', '<\/', $json) . '</script>' . "\n";
}
add_action('wp_head', 'parisii_optique_output_local_business_schema', 20);
